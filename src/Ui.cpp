void Ui::setLanguage(const QString &language) {english=language=="en";}
QString Ui::text(const QString &source) {
    if (!english) return source;
    if (translations.contains(source)) return translations[source];
    for (auto it=translations.begin();it!=translations.end();++it) {
        if (!it.key().contains('%')) continue;
        QString pattern;qsizetype previous=0;
        auto placeholders=QRegularExpression("%[1-9]").globalMatch(it.key());
        while(placeholders.hasNext()){const auto placeholder=placeholders.next();pattern+=QRegularExpression::escape(it.key().mid(previous,placeholder.capturedStart()-previous))+"(.*?)";previous=placeholder.capturedEnd();}
        pattern+=QRegularExpression::escape(it.key().mid(previous));
        const auto match=QRegularExpression("^"+pattern+"$",QRegularExpression::DotMatchesEverythingOption).match(source);
        if (match.hasMatch()) {QString result=it.value();for(int i=1;i<=match.lastCapturedIndex();++i) result.replace("%"+QString::number(i),match.captured(i));return result;}
    }
    if (source.contains('\n')) {QStringList lines;for (const auto &line:source.split('\n')) lines.append(text(line));return lines.join('\n');}
    return source;
}
void Ui::capture(QWidget *root) {
    for (auto *w:widgets(root)) {
        if(w->property("dynamicText").toBool()) continue;
        if(auto *label=qobject_cast<QLabel*>(w)) {label->setTextFormat(Qt::PlainText);w->setProperty("sourceText",label->text());}
        else if(auto *button=qobject_cast<QAbstractButton*>(w)) w->setProperty("sourceText",button->text());
        else if(auto *edit=qobject_cast<QLineEdit*>(w)) w->setProperty("sourcePlaceholder",edit->placeholderText());
        else if(auto *combo=qobject_cast<QComboBox*>(w)) for(int i=0;i<combo->count();++i) combo->setItemData(i,combo->itemText(i),Qt::UserRole+10);
    }
}
void Ui::refresh(QWidget *root) {
    for(auto *w:widgets(root)) {
        if(w->property("dynamicText").toBool()) continue;
        if(auto *label=qobject_cast<QLabel*>(w)) {if(w->property("sourceText").isValid()) label->setText(text(w->property("sourceText").toString()));}
        else if(auto *button=qobject_cast<QAbstractButton*>(w)) {if(w->property("sourceText").isValid()) button->setText(text(w->property("sourceText").toString()));}
        else if(auto *edit=qobject_cast<QLineEdit*>(w)) edit->setPlaceholderText(text(w->property("sourcePlaceholder").toString()));
        else if(auto *combo=qobject_cast<QComboBox*>(w)) {const bool blocked=combo->blockSignals(true);for(int i=0;i<combo->count();++i) {const auto source=combo->itemData(i,Qt::UserRole+10);if(source.isValid()) combo->setItemText(i,text(source.toString()));}combo->blockSignals(blocked);}
    }
}
